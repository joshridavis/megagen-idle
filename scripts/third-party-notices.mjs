// Writes THIRD_PARTY_NOTICES.md: the license of every package shipped in the
// game build (production dependencies and theirs; type-only packages left out).
// Run after changing dependencies: npm run notices (0.67).
import { execSync } from 'node:child_process';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const TYPE_ONLY = /^@types\/|^csstype$/;
const dirs = execSync('npm ls --omit=dev --all --parseable', { encoding: 'utf8' }).trim().split('\n').slice(1);
const seen = new Map();
for (const dir of dirs) {
  const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
  if (TYPE_ONLY.test(pkg.name) || seen.has(pkg.name)) continue;
  const file = readdirSync(dir).find((f) => /^licen[cs]e/i.test(f));
  seen.set(pkg.name, { version: pkg.version, license: pkg.license, text: file ? readFileSync(join(dir, file), 'utf8').trim() : '(no license file in the package)' });
}
const names = [...seen.keys()].sort();
let out = '# Third-party notices\n\nMegaGen Idle ships the following open-source packages. Generated by `npm run notices`; do not edit by hand.\n\n';
out += names.map((n) => `- ${n} ${seen.get(n).version} (${seen.get(n).license})`).join('\n') + '\n';
for (const n of names) out += `\n## ${n} ${seen.get(n).version}\n\n\`\`\`\n${seen.get(n).text}\n\`\`\`\n`;
writeFileSync('THIRD_PARTY_NOTICES.md', out);
console.log(`THIRD_PARTY_NOTICES.md written: ${names.length} packages.`);
